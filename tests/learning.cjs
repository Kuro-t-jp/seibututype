const assert = require('node:assert/strict');
const L = require('../src/learning.js');
const day = 86400000, now = 1800000000000;
const words = [{t:'細胞',unit:'B1a',c:'細胞'},{t:'免疫',unit:'B2b',c:'恒常性'},{t:'転写',unit:'A3a',c:'遺伝'},{t:'対照実験',unit:'P',c:'基礎'}];
const units = {B1a:{subject:'生物基礎'},B2b:{subject:'生物基礎'},A3a:{subject:'生物'},P:{subject:'生物基礎・生物'}};
assert.deepEqual(L.filter(words,units,{subject:'生物基礎',unit:'all',cats:['ALL']}).map(w=>w.t),['細胞','免疫','対照実験']);
assert.equal(L.filter(words,units,{subject:'生物基礎',unit:'B2b',cats:['遺伝']}).length,0);
let state = {};
state = L.record(state,'細胞','type',{ok:true},now);
assert.equal(L.lane(state,'細胞','recall').stage,0,'copying is not retrieval');
state = L.record(state,'細胞','quiz',{ok:true},now);
assert.equal(L.lane(state,'細胞','quiz').due,now+day);
assert.equal(L.lane(state,'細胞','recall').stage,0,'recognition is separate from recall');
state = L.record(state,'細胞','quiz',{ok:true},now+1000);
assert.equal(L.lane(state,'細胞','quiz').stage,1,'same day repetition cannot inflate retention');
assert.equal(L.lane(state,'細胞','quiz').due,now+day);
state = L.record(state,'細胞','quiz',{ok:true},now+day);
assert.equal(L.lane(state,'細胞','quiz').stage,2);
assert.equal(L.lane(state,'細胞','quiz').due,now+4*day);
state = L.record(state,'細胞','quiz',{ok:true,uncertain:true},now+4*day);
assert.equal(L.lane(state,'細胞','quiz').stage,0);
assert.equal(L.lane(state,'細胞','quiz').due,now+4*day);
const old=JSON.stringify(state);
state=L.record(state,'細胞','quiz',{ok:false,incomplete:true},now+5*day);
assert.equal(JSON.stringify(state),old,'unfinished questions are not attempts');
assert.deepEqual(L.queue(words,state,'quiz','due',now+4*day).map(w=>w.t),['細胞']);
assert.equal(L.queue(words,{},'quiz','due',now).length,0);
assert.equal(L.queue(words,state,'quiz','recommended',now+4*day)[0].t,'細胞');
assert.deepEqual(L.sanitize(null,words),{});
assert.deepEqual(L.sanitize({bad:{},細胞:{quiz:{stage:Infinity,due:'bad'}}},words),{});
console.log('PASS learning: subject scope, independent skills, spacing, uncertainty, incomplete, due queue, corrupt storage');
// Typing is exposure: recommend unseen terms before already copied terms.
let exposure=L.record({},'細胞','type',{ok:true},now);
assert.equal(L.queue(words,exposure,'type','recommended',now)[0].t,'免疫');
